/**
 * Worker #30 deterministic cancellation isolation. Exercises the *actual*
 * proposed staging SQLite budget, and separately an explicit TEST-ONLY
 * monotonic owner epoch + opaque witness contract. No signed native witness.
 */
import test from 'node:test';
import assert from 'node:assert/strict';
import {createHash} from 'node:crypto';
import {DatabaseSync} from 'node:sqlite';
import {
  ARTIFACT_CHUNK_BYTES,initArtifactBudgetFixture,StagingArtifactByteBudget,
} from '../src/ops/scale-v2-artifact-byte-budget-staging.js';

const N=ARTIFACT_CHUNK_BYTES;
const HASH=createHash('sha256').update('worker30-staged-pending-chunk').digest('hex');
const WRONG_HASH=createHash('sha256').update('worker30-forged-ack').digest('hex');
const WHEN=new Date('2026-10-21T19:00:00Z');
const OWN_A='qa30-owner-noisy',OWN_B='qa30-owner-quiet';
type Owner=typeof OWN_A|typeof OWN_B;
const open=(owner:Owner,suffix:string)=>({
  ownerId:owner,deviceId:'device-'+owner,projectId:'project-qa30-isolated',
  sessionId:'session-'+suffix,rootInvocationId:'root30-'+suffix,
  sizeBytes:2*N,sourceSha256:HASH,physicalFreeBytes:8*1024**3,now:WHEN,
});
const chunk=(owner:Owner,suffix:string,requestId:string)=>({
  ownerId:owner,deviceId:'device-'+owner,projectId:'project-qa30-isolated',
  sessionId:'session-'+suffix,requestId,offsetBytes:0,
  byteCount:N,chunkSha256:HASH,now:WHEN,
});
type Lease={owner:Owner;id:string;epoch:number;state:'PENDING'|'UNKNOWN'|'RELEASED'};
class FixtureEpochFencer {
  private readonly epochs=new Map<Owner,number>([[OWN_A,5],[OWN_B,8]]);
  private readonly leases=new Map<string,Lease>();
  private readonly attestations=new WeakMap<object,{
    owner:Owner;id:string;epoch:number;writerStopped:boolean;readbackSha:string;
  }>();
  ownerEpoch(owner:Owner){return this.epochs.get(owner)!;}
  used(owner:Owner){
    return [...this.leases.values()].filter(l=>l.owner===owner&&l.state!=='RELEASED')
      .length*N;
  }
  reserve(owner:Owner,id:string,epoch:number){
    if(epoch!==this.ownerEpoch(owner))return 'STALE_EPOCH';
    if(this.leases.has(id))return 'DUPLICATE';
    if(this.used(owner)+N>2*N)return 'THROTTLED';
    this.leases.set(id,{owner,id,epoch,state:'PENDING'});
    return 'RESERVED';
  }
  cancelledUnknown(owner:Owner,id:string){
    const x=this.leases.get(id);
    if(!x||x.owner!==owner||x.state==='RELEASED')return 'DENIED_SCOPE';
    x.state='UNKNOWN';return 'MUTATION_UNKNOWN';
  }
  // TEST-ONLY issuer simulates an external immutable readback after a
  // writer-stop. In production this must be authenticated by another trust
  // boundary, not generated by client input or this source QA.
  mint(owner:Owner,id:string,epoch:number,writerStopped:boolean,sha:string){
    const token=Object.freeze({});
    this.attestations.set(token,{owner,id,epoch,writerStopped,readbackSha:sha});
    return token;
  }
  rePair(owner:Owner){this.epochs.set(owner,this.ownerEpoch(owner)+1);}
  release(owner:Owner,id:string,epoch:number,sha:string,token:object){
    const x=this.leases.get(id);
    if(!x||x.owner!==owner)return 'DENIED_OWNER';
    if(x.state==='RELEASED')return 'ALREADY_RELEASED';
    if(x.state!=='UNKNOWN')return 'UNKNOWN_REQUIRED';
    if(epoch!==this.ownerEpoch(owner)||epoch!==x.epoch)return 'STALE_EPOCH';
    const receipt=this.attestations.get(token);
    if(!receipt||receipt.owner!==owner||receipt.id!==id||
      receipt.epoch!==epoch||!receipt.writerStopped||
      receipt.readbackSha!==sha)return 'UNVERIFIED_POSTCONDITION';
    x.state='RELEASED';return 'RELEASED';
  }
}
test('QA30 staged pending: forged ACK, foreign receipt and cancellation do not double-refund storage',()=>{
  const db=new DatabaseSync(':memory:');
  initArtifactBudgetFixture(db);
  const stage=new StagingArtifactByteBudget(db);
  const fence=new FixtureEpochFencer();
  try{
    assert.equal(stage.begin(open(OWN_A,'tenant-a')),'RESERVED');
    assert.equal(stage.begin(open(OWN_B,'tenant-b')),'RESERVED');
    const a=chunk(OWN_A,'tenant-a','request30-pending-a');
    const b=chunk(OWN_B,'tenant-b','request30-pending-b');
    assert.equal(stage.stageChunk(a),'CHUNK_PENDING');
    assert.equal(stage.stageChunk(b),'CHUNK_PENDING');
    assert.equal(fence.reserve(OWN_A,a.requestId,5),'RESERVED');
    assert.equal(fence.reserve(OWN_A,'request30-pending-other-a',5),'RESERVED');
    assert.equal(fence.reserve(OWN_A,'request30-overbudget-a',5),'THROTTLED');
    assert.equal(fence.reserve(OWN_B,b.requestId,8),'RESERVED');
    assert.equal(fence.cancelledUnknown(OWN_A,a.requestId),'MUTATION_UNKNOWN');

    // A stale/foreign caller cannot alter the actual staging source state.
    assert.equal(stage.stageChunk({...a,ownerId:OWN_B,deviceId:'device-'+OWN_B}),
      'DENIED_REPLAY');
    assert.equal(stage.stageChunk(a),'CHUNK_PENDING','no replay of writer');
    assert.equal(stage.stageChunk({...a,requestId:'request30-second-a'}),
      'DENIED_PENDING');
    assert.equal(stage.commitChunk({...a,storedSha256:WRONG_HASH,durableStorageVerified:true}),
      'DENIED_REPLAY');
    assert.equal(stage.acknowledgeDeletion({
      ...a,durableDeletionVerified:true,
    }),'DENIED_STATE','OPEN session cannot use purported deletion receipt');
    assert.equal(stage.finalize({
      ...a,storedSha256:HASH,storedSizeBytes:2*N,durableStorageVerified:true,
    }),'DENIED_STATE');
    assert.equal(fence.used(OWN_A),2*N);
    assert.equal(fence.used(OWN_B),N);

    // After re-pair, an apparently valid OLD token does not unlock memory.
    const oldToken=fence.mint(OWN_A,a.requestId,5,true,HASH);
    fence.rePair(OWN_A);
    assert.equal(fence.release(OWN_A,a.requestId,5,HASH,oldToken),'STALE_EPOCH');
    assert.equal(fence.release(OWN_A,a.requestId,6,HASH,oldToken),'STALE_EPOCH');
    assert.equal(fence.reserve(OWN_A,'request30-fresh-after-repair',6),'THROTTLED');
    assert.equal(fence.used(OWN_A),2*N);
    assert.equal(fence.used(OWN_B),N);
    assert.equal(fence.reserve(OWN_B,'request30-quiet-second',8),'RESERVED',
      'quiet tenant remains able to use its isolated free budget');
    assert.equal(fence.used(OWN_B),2*N);

    const pending=(db.prepare(
      "SELECT COUNT(*) AS n FROM budget_artifact_chunks WHERE state='PENDING'"
    ).get() as {n:number}).n;
    const reserved=(db.prepare(
      "SELECT COALESCE(SUM(size_bytes),0) AS n FROM budget_artifact_sessions WHERE state<>'RELEASED'"
    ).get() as {n:number}).n;
    const aOffset=(db.prepare(
      'SELECT offset_bytes AS n FROM budget_artifact_sessions WHERE session_id=?'
    ).get('session-tenant-a') as {n:number}).n;
    assert.deepEqual({pending,reserved,aOffset},{pending:2,reserved:4*N,aOffset:0});
    process.stdout.write('QA30_REPAIR_PENDING_FENCE '+JSON.stringify({
      parentHead:'8b08ede8db29fd9a95abb762b238601def07082d',
      parserOwnerSourceSha:'cf58e6882e44968698f3f548b353287ba1698747',
      workflowCheckoutSha:process.env.GITHUB_SHA??null,
      classification:'ACTUAL_STAGING_SQLITE_AND_TEST_ONLY_EPOCH_FENCER',
      lostAckMutationUnknown:true,ownerRePairRevokesOldWitness:true,
      keptPendingReceipts:pending,storageReservedBytes:reserved,
      oldOwnerMemoryUsedBytes:fence.used(OWN_A),
      quietOwnerMemoryUsedBytes:fence.used(OWN_B),
      independentPhysicalWriterProof:false,realAgentWrites:0,cloudflareCost:null,
    })+'\n');
  }finally{db.close();}
});
