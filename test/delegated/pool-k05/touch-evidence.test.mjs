import test from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { validateTouchEvidence, summarizeTouchEvidence } from './touch-evidence.mjs';

const fixture = JSON.parse(readFileSync(new URL('./touch-evidence.fixture.json', import.meta.url), 'utf8'));
const copy = () => structuredClone(fixture);
const rules = (record) => validateTouchEvidence(record).map(({ rule }) => rule);

test('T-253: source-only CSS candidate stays NOT_RUN with no acceptance claim', () => {
  assert.deepEqual(validateTouchEvidence(fixture), []);
  assert.deepEqual(summarizeTouchEvidence(fixture), {
    valid: true, observedUnverified: 0, notRun: 1, accessibilityAccepted: false,
  });
});

test('T-253: explicit PASS/FAIL labels are never generated by source-only evidence', () => {
  for (const status of ['PASS', 'FAIL', 'SUCCESS', 'UNKNOWN']) {
    const item = copy(); item.targets[0].status = status;
    assert.ok(rules(item).includes('unsupported-status'));
  }
});

test('T-253: CSS source cannot be passed off as measured observation', () => {
  const item = copy();
  item.targets[0].status = 'OBSERVED';
  item.targets[0].measurement = { widthPx: 44, heightPx: 44, spacingPx: 8 };
  item.targets[0].evidence.artifact = 'claimed.png';
  assert.ok(rules(item).includes('source-only-observation'));
});

test('T-253: claimed observation requires artifact and strict finite measurements', () => {
  const item = copy();
  item.targets[0].status = 'OBSERVED';
  item.targets[0].evidence.kind = 'browser';
  item.targets[0].measurement = { widthPx: 44, heightPx: 24, spacingPx: 8 };
  assert.ok(rules(item).includes('missing-evidence-artifact'));
  item.targets[0].evidence.artifact = 'review-required.png';
  assert.deepEqual(rules(item), []);
  assert.equal(summarizeTouchEvidence(item).accessibilityAccepted, false);
  for (const value of [NaN, Infinity, -1, 0, '44']) {
    item.targets[0].measurement.widthPx = value;
    assert.ok(rules(item).includes('invalid-measurement'), String(value));
  }
});

test('T-253: missing or negative spacing cannot masquerade as a valid measurement', () => {
  const item = copy();
  item.targets[0].status = 'OBSERVED';
  item.targets[0].evidence = { kind: 'manual', artifact: 'independent-review-required' };
  item.targets[0].measurement = { widthPx: 40, heightPx: 40, spacingPx: -2 };
  assert.ok(rules(item).includes('invalid-measurement'));
  delete item.targets[0].measurement.spacingPx;
  assert.ok(rules(item).includes('invalid-measurement'));
});

test('T-253: duplicate IDs, missing reason, missing targets and bad viewport are rejected', () => {
  const item = copy();
  item.targets.push(structuredClone(item.targets[0]));
  assert.ok(rules(item).includes('duplicate-target-id'));
  item.targets[0].reason = '';
  assert.ok(rules(item).includes('missing-not-run-reason'));
  item.targets = [];
  assert.ok(rules(item).includes('missing-targets'));
  item.targets = copy().targets;
  item.viewport.widthPx = Infinity;
  assert.ok(rules(item).includes('invalid-viewport'));
});

test('T-253: missing schema, bad page and leaked file path are rejected', () => {
  assert.ok(rules({ schemaVersion: 2 }).includes('unsupported-schema'));
  const item = copy(); item.page = '/users/example/web/index.html';
  assert.ok(rules(item).includes('invalid-page'));
  item.page = 'web/../../secret.html';
  assert.ok(rules(item).includes('invalid-page'));
});

test('T-253: fixture CSS selector is grounded, without claiming pixel measurement', () => {
  const css = readFileSync(new URL('../../../web/styles.css', import.meta.url), 'utf8');
  assert.match(css, /\.filter-button,\.layout-button\s*\{[^}]*min-height:36px/);
  assert.equal(fixture.targets[0].measurement, null);
});
