import test from 'node:test';
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import path from 'node:path';
const qa=path.resolve('docs/qa');
const load=(n:string)=>JSON.parse(readFileSync(path.join(qa,n),'utf8')) as any;
test('21 Oct exact-main source 21/21 pass does not close physical acceptance',()=>{
 const m=load('cross-project-final-acceptance.json');
 const x=load('QA_20261021_EXACT_HEAD_EVIDENCE.json');
 assert.equal(x.reviewedMainSha,'37d68d938b9c94b8647b92fb592a2b30c075427c');
 assert.equal(m.baselineSha,'754cc4364822be5fda528f54042fb22a84f19924');
 assert.equal(x.mainCi.runId,39558249914);
 assert.equal(x.mainCi.status,'PASS');
 assert.equal(x.localMainRepro.pass,21);
 assert.equal(x.localMainRepro.fail,0);
 assert.equal(x.localMainRepro.skip,0);
 assert.equal(m.requirements.length,22);
 assert.ok(m.requirements.every((r:any)=>['staging','production','incident'].every(k=>r.levels[k].status==='BLOCKED')));
});
test('597 child merged into 596 feature branch, while 598 red and 608 green remain separate',()=>{
 const e=load('QA_20261021_EXACT_HEAD_EVIDENCE.json');
 const p=load('PR_SOURCE_AND_RELEASE_GATES.json');
 const pr=(n:number)=>p.entries.find((x:any)=>x.pr===n);
 assert.equal(pr(597).prState,'MERGED_TO_596_BRANCH');
 assert.equal(pr(597).ci.status,'PASS');
 assert.equal(pr(597).ci.runId,39502962661);
 assert.equal(pr(596).headSha,'335046569a38f3a1a3fc82bf851f9b7df7640fdb');
 assert.equal(pr(596).ci.runId,39557944551);
 assert.equal(pr(596).ci.status,'PASS');
 assert.equal(pr(598).ci.runId,39502304557);
 assert.equal(pr(598).ci.status,'FAIL');
 assert.equal(pr(608).ci.status,'PASS');
 assert.equal(pr(608).ci.runId,39503650650);
 assert.ok(e.branchSnapshots.some((x:any)=>x.pr===608&&x.releaseReadinessCi===39503650638));
 assert.equal(pr(601).ci.runId,39492176139);
 assert.equal(pr(603).ci.runId,39492384138);
 assert.equal(pr(597).production,'BLOCKED');
 assert.equal(pr(608).production,'BLOCKED');
 assert.equal(load('cross-project-final-acceptance.json').requirements.find((x:any)=>x.id==='R15').levels.source.status,'FAIL');
});
