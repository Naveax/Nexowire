#!/usr/bin/env node
// Dependency-free, intentionally conservative source-HTML accessibility audit.
// This is not a browser, accessibility-tree, or JavaScript-rendered DOM test.
import { readFileSync } from 'node:fs';
import { resolve, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = fileURLToPath(new URL('../../../', import.meta.url));
const DEFAULT_PAGES = [
  'web/index.html', 'web/connect.html', 'web/admin.html',
  'web/custom-usage-consent-preview.html',
];
const VOID = new Set(['area', 'base', 'br', 'col', 'embed', 'hr', 'img', 'input',
  'link', 'meta', 'param', 'source', 'track', 'wbr']);
const FORM = new Set(['input', 'select', 'textarea']);
const LABELABLE = new Set(['button', 'input', 'meter', 'output', 'progress', 'select', 'textarea']);
const WIDGETS = new Set(['button', 'link', 'checkbox', 'radio', 'switch', 'tab', 'menuitem', 'option', 'slider']);
const REFERENCES = ['aria-labelledby', 'aria-describedby', 'aria-controls', 'aria-errormessage'];

function parseAttrs(openTag) {
  const rest = openTag.replace(/^<\s*[\w:-]+/, '').replace(/\/?>\s*$/, '');
  const attrs = {};
  const pattern = /([^\s=/>]+)(?:\s*=\s*(?:"([^"]*)"|'([^']*)'|([^\s"'`=<>]+)))?/g;
  for (const match of rest.matchAll(pattern)) {
    attrs[match[1].toLowerCase()] = match[2] ?? match[3] ?? match[4] ?? '';
  }
  return attrs;
}

function parseStaticHtml(html) {
  const root = { tag: '#root', attrs: {}, children: [], parent: null, offset: 0 };
  const nodes = [];
  const stack = [root];
  // Script/style and comments are opaque; dynamic DOM generated by JS is out of scope.
  const tokens = /<!--[\s\S]*?-->|<(script|style)\b[^>]*>[\s\S]*?<\/\1\s*>|<\/?[a-z][^>]*>|[^<]+/gi;
  for (const match of html.matchAll(tokens)) {
    const token = match[0];
    if (token.startsWith('<!--')) continue;
    if (/^<(?:script|style)\b/i.test(token) && /<\/(?:script|style)\s*>$/i.test(token)) continue;
    if (/^<\/(?:[a-z])/i.test(token)) {
      const name = token.match(/^<\/\s*([\w:-]+)/i)?.[1].toLowerCase();
      if (name) {
        const index = stack.findLastIndex((entry) => entry.tag === name);
        if (index > 0) stack.length = index;
      }
      continue;
    }
    if (/^<[a-z]/i.test(token)) {
      const tag = token.match(/^<\s*([\w:-]+)/i)?.[1].toLowerCase();
      if (!tag) continue;
      const node = { tag, attrs: parseAttrs(token), parent: stack.at(-1),
        children: [], offset: match.index };
      stack.at(-1).children.push(node);
      nodes.push(node);
      if (!VOID.has(tag) && !/\/\s*>$/.test(token) && !/^(script|style)$/.test(tag)) {
        stack.push(node);
      }
    } else {
      stack.at(-1).children.push(token);
    }
  }
  return nodes;
}

function plainText(node, includeHidden = false) {
  if (typeof node === 'string') return node;
  if (!includeHidden && (node.attrs['aria-hidden'] === 'true' || 'hidden' in node.attrs)) return '';
  if (node.tag === 'img') return node.attrs.alt ?? '';
  return node.children.map((child) => plainText(child, includeHidden)).join(' ').replace(/\s+/g, ' ').trim();
}

function ancestor(node, tag) {
  for (let parent = node.parent; parent; parent = parent.parent) {
    if (parent.tag === tag) return parent;
  }
  return null;
}

function isNativeKeyboard(node) {
  return node.tag === 'button' || node.tag === 'select' || node.tag === 'textarea' ||
    node.tag === 'summary' || (node.tag === 'a' && 'href' in node.attrs) ||
    (node.tag === 'input' && node.attrs.type !== 'hidden');
}

function isFocusable(node) {
  return isNativeKeyboard(node) || ('tabindex' in node.attrs && Number(node.attrs.tabindex) >= 0);
}

function isHiddenFromAssistiveTech(node) {
  for (let current = node; current; current = current.parent) {
    if (current.attrs['aria-hidden'] === 'true') return true;
  }
  return false;
}

export function auditHtml(html, file = '<fixture>') {
  const nodes = parseStaticHtml(html);
  const ids = new Map();
  const labels = nodes.filter((node) => node.tag === 'label');
  const findings = [];
  const stats = { elements: nodes.length, formControls: 0, buttons: 0,
    links: 0, liveRegions: 0, errorPanels: 0, keyboardCandidates: 0 };
  const add = (rule, node, detail) => {
    const line = html.slice(0, node.offset).split('\n').length;
    findings.push({ rule, file, line, detail });
  };

  for (const node of nodes) {
    const id = node.attrs.id;
    if (!id) continue;
    if (ids.has(id)) add('duplicate-id', node, `id="${id}" is duplicated`);
    else ids.set(id, node);
  }

  function referencedName(node) {
    const ref = node.attrs['aria-labelledby'];
    // An explicit aria-labelledby may reference text within a hidden subtree.
    if (ref !== undefined) return ref.split(/\s+/).map((id) => plainText(ids.get(id) ?? '', true)).join(' ').trim();
    if (node.attrs['aria-label'] !== undefined) return node.attrs['aria-label'].trim();
    return '';
  }

  function associatedLabel(node) {
    const id = node.attrs.id;
    return labels.filter((label) => (id && label.attrs.for === id) ||
      (!('for' in label.attrs) && ancestor(node, 'label') === label))
      .map(plainText).join(' ').trim();
  }

  for (const node of nodes) {
    const { tag, attrs } = node;
    if (isFocusable(node) && isHiddenFromAssistiveTech(node)) {
      add('hidden-focusable', node, `${tag} is focusable inside aria-hidden subtree`);
    }

    for (const attribute of REFERENCES) {
      if (!(attribute in attrs)) continue;
      const targetIds = attrs[attribute].trim().split(/\s+/).filter(Boolean);
      if (!targetIds.length) add('empty-reference', node, `${attribute} is empty`);
      for (const target of targetIds) {
        if (!ids.has(target)) add('broken-reference', node, `${attribute} references missing #${target}`);
      }
    }
    if ('aria-live' in attrs && !['off', 'polite', 'assertive'].includes(attrs['aria-live'])) {
      add('invalid-live', node, `aria-live="${attrs['aria-live']}" is invalid`);
    }
    if (['status', 'alert'].includes(attrs.role) && attrs['aria-live'] === 'off') {
      add('suppressed-live', node, `role="${attrs.role}" overrides its live announcement with off`);
    }
    if (attrs.role === 'status' || attrs.role === 'alert' || 'aria-live' in attrs) stats.liveRegions++;

    if (tag === 'label' && 'for' in attrs) {
      const target = ids.get(attrs.for);
      if (!target || !LABELABLE.has(target.tag) || target.attrs.type === 'hidden') {
        add('broken-label', node, `label for="${attrs.for}" has no labelable target`);
      }
      if (!plainText(node)) add('empty-label', node, `label for="${attrs.for}" has no text`);
    }

    if (FORM.has(tag) && attrs.type !== 'hidden') {
      stats.formControls++;
      if (!referencedName(node) && !associatedLabel(node) && !(tag === 'input' &&
        ['submit', 'reset', 'button', 'image'].includes(attrs.type) &&
        (attrs.value || attrs.alt))) {
        add('unnamed-control', node, `${tag} ${attrs.id ? '#' + attrs.id : '(no id)'} lacks an accessible label`);
      }
    }
    if (tag === 'button') stats.buttons++;
    if (tag === 'a' && 'href' in attrs) stats.links++;
    if (tag === 'button' || (tag === 'a' && 'href' in attrs) ||
        (WIDGETS.has(attrs.role) && !FORM.has(tag))) {
      if (!referencedName(node) && !plainText(node)) {
        add('unnamed-action', node, `${tag} ${attrs.role ? 'role=' + attrs.role : ''} has no accessible name`);
      }
    }
    if (isNativeKeyboard(node) || WIDGETS.has(attrs.role) || 'onclick' in attrs) {
      stats.keyboardCandidates++;
    }
    if ((WIDGETS.has(attrs.role) || 'onclick' in attrs) && !isNativeKeyboard(node) &&
        (!('tabindex' in attrs) || Number(attrs.tabindex) < 0)) {
      add('keyboard-unreachable', node, `interactive ${tag} must be keyboard-focusable`);
    }
    if ('onclick' in attrs && !isNativeKeyboard(node) && !WIDGETS.has(attrs.role)) {
      add('missing-interactive-role', node, `${tag} uses onclick without an interactive role`);
    }
    if (attrs.role === 'tab' && !attrs['aria-controls']) {
      add('tab-without-panel', node, `tab needs aria-controls`);
    }
    if (attrs.class?.split(/\s+/).includes('error-panel')) {
      stats.errorPanels++;
      if (!['alert', 'status'].includes(attrs.role) && !['polite', 'assertive'].includes(attrs['aria-live'])) {
        add('silent-error-panel', node, `error-panel lacks alert/status/live semantics`);
      }
      if (!plainText(node)) add('empty-error-panel', node, `error-panel lacks initial readable content`);
    }
  }
  if (!nodes.some((node) => node.tag === 'meta' && node.attrs.name?.toLowerCase() === 'viewport' &&
      /\bwidth\s*=\s*device-width\b/i.test(node.attrs.content ?? ''))) {
    add('missing-mobile-viewport', { offset: 0 }, 'no meta viewport with width=device-width');
  }
  return { file, findings, stats };
}

export function auditErrorBindings(html, js, file, { panel, message }) {
  const result = auditHtml(html, file);
  const nodes = parseStaticHtml(html);
  const ids = new Map(nodes.filter((node) => node.attrs.id).map((node) => [node.attrs.id, node]));
  for (const id of [panel, message]) {
    if (!ids.has(id)) result.findings.push({ rule: 'missing-error-id', file, line: 0, detail: `missing #${id}` });
  }
  if (ids.has(panel) && ids.has(message)) {
    let parent = ids.get(message).parent;
    while (parent && parent !== ids.get(panel)) parent = parent.parent;
    if (!parent) result.findings.push({ rule: 'error-message-outside-panel', file, line: 0,
      detail: `#${message} is not inside #${panel}` });
  }
  const read = (id, prop) => new RegExp(`\\$\\(['"]${id}['"]\\)\\.${prop}\\b`);
  if (!read(message, 'textContent').test(js)) {
    result.findings.push({ rule: 'error-binding', file, line: 0,
      detail: `error message #${message} is not assigned with textContent` });
  }
  if (read(message, 'innerHTML').test(js)) {
    result.findings.push({ rule: 'unsafe-error-sink', file, line: 0,
      detail: `error message #${message} uses innerHTML` });
  }
  return result;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const pages = process.argv.slice(2).length ? process.argv.slice(2) : DEFAULT_PAGES;
  let failed = 0;
  for (const page of pages) {
    const path = resolve(page);
    const html = readFileSync(path, 'utf8');
    const file = relative(ROOT, path);
    const matchingJs = new Map([
      ['web/index.html', ['web/app.js', 'error-panel', 'error-message']],
      ['web/connect.html', ['web/connect.js', 'error-panel', 'error-message']],
      ['web/admin.html', ['web/admin.js', 'admin-error', 'admin-error-message']],
    ]).get(file);
    const result = matchingJs
      ? auditErrorBindings(html, readFileSync(resolve(ROOT, matchingJs[0]), 'utf8'), file,
        { panel: matchingJs[1], message: matchingJs[2] })
      : auditHtml(html, file);
    console.log(`${file}: ${result.stats.formControls} form fields, ${result.stats.buttons} buttons, ` +
      `${result.stats.links} links, ${result.stats.liveRegions} live regions, ${result.findings.length} findings`);
    for (const finding of result.findings) {
      console.log(`  ${finding.rule} ${finding.line || '-'}: ${finding.detail}`);
    }
    failed += result.findings.length;
  }
  console.log(`STATIC SOURCE ONLY — ${failed ? 'FINDINGS' : 'PASS'}; browser/keyboard/touch/JS-rendered DOM NOT_RUN`);
  if (failed) process.exitCode = 1;
}
